    ["trap"] = true,
    ["multiworld"] = true
}

IMPORTANT_HINT_TEXT = ""

local function findObject(codes)
    for _, code in ipairs(codes) do
        local object = Tracker:FindObjectForCode(code)
        if object then
            return object
        end
    end

    return nil
end

local function hintItemName(stage)
    return IMPORTANT_ITEMS[stage] or "Unknown"
end

local function hintRegionName(stage)
    return REGION_NAMES[stage] or "Unknown"
end

function ResetHintState()
    for _, source in ipairs(HINT_SOURCES) do
        local itemObject = Tracker:FindObjectForCode(source.item_code)
        local regionObject = Tracker:FindObjectForCode(source.region_code)

        if itemObject then
            itemObject.CurrentStage = 0
        end

        if regionObject then
            regionObject.CurrentStage = 0
        end
    end

    IMPORTANT_HINT_TEXT = ""
end

function UpdateHintDisplays()
    for _, source in ipairs(HINT_SOURCES) do
        local itemObject = Tracker:FindObjectForCode(source.item_code)
        local regionObject = Tracker:FindObjectForCode(source.region_code)
        local locationObject = findObject(source.location_codes)
        local displayObject = Tracker:FindObjectForCode(source.display_code)

        if itemObject and regionObject and locationObject then
            local itemName = hintItemName(itemObject.CurrentStage)
            local regionName = hintRegionName(regionObject.CurrentStage)

            locationObject.Caption = itemName .. " -> " .. regionName

            if displayObject then
                displayObject:SetOverlay(itemName .. " -> " .. regionName)
                displayObject:SetOverlayAlign("left")
                displayObject:SetOverlayFontSize(12)
            end
        end
    end
end

function BuildImportantHintList()
    local output = ""

    for _, source in ipairs(HINT_SOURCES) do
        local itemObject = Tracker:FindObjectForCode(source.item_code)
        local regionObject = Tracker:FindObjectForCode(source.region_code)

        if itemObject and regionObject then
            local itemName = hintItemName(itemObject.CurrentStage)
            local regionName = hintRegionName(regionObject.CurrentStage)

            if IMPORTANT_FILTER[itemName] then
                output = output .. itemName .. " -> " .. regionName .. "\n"
            end
        end
    end

    IMPORTANT_HINT_TEXT = output

    local panel = Tracker:FindObjectForCode("important_hint_panel")
    if panel then
        panel:SetOverlay(output ~= "" and output or "Important Hints")
        panel:SetOverlayAlign("left")
        panel:SetOverlayFontSize(12)
    end
end

function RefreshHintSystem()
    UpdateHintDisplays()
    BuildImportantHintList()
end

function RegisterHintWatches()
    for _, source in ipairs(HINT_SOURCES) do
        ScriptHost:AddWatchForCode(
            source.name .. "_item_watch",
            source.item_code,
            RefreshHintSystem
        )

        ScriptHost:AddWatchForCode(
            source.name .. "_region_watch",
            source.region_code,
            RefreshHintSystem
        )
    end
end

RegisterHintWatches()
